import AppKit

/// Something new on the general pasteboard, read on the main thread.
struct ClipboardCapture {
    enum Content {
        case text(String)
        case url(String)
        case files([String])
        /// Raw image data as found on the pasteboard (PNG or TIFF); the store converts it.
        case image(Data)
    }

    var content: Content
    var date: Date
    var sourceBundleID: String?
    var sourceAppName: String?
}

/// Polls `NSPasteboard.general.changeCount` every 0.5 s (there is no change notification) and
/// reports what was copied, skipping private/transient data, excluded apps, oversized content
/// and iEdge's own writes (docs/SPEC.md §1.3).
@MainActor final class ClipboardMonitor {
    static let interval: TimeInterval = 0.5
    static let maxTextBytes = 200 * 1024
    static let maxImageBytes = 20 * 1024 * 1024

    /// Marker types from nspasteboard.org: passwords and other concealed data, data meant to live
    /// only briefly, and data a tool generated on its own (not a user copy).
    nonisolated static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    var onCapture: ((ClipboardCapture) -> Void)?
    /// Bundle ids whose copies are ignored (read on every change, so settings apply at once).
    var excludedBundleIDs: () -> [String] = { [] }

    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount: Int

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        // What was on the pasteboard before launch is not a new copy.
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: Self.interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call right after iEdge writes to the pasteboard, so that write is not recorded as a copy.
    func ignoreCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: Pure rules

    /// True when the pasteboard carries one of the nspasteboard.org privacy markers.
    nonisolated static func shouldIgnore(types: [String]) -> Bool {
        types.contains { ignoredTypes.contains($0) }
    }

    nonisolated static func isExcluded(bundleID: String?, excluded: [String]) -> Bool {
        guard let bundleID else { return false }
        return excluded.contains { $0.caseInsensitiveCompare(bundleID) == .orderedSame }
    }

    /// A single line that parses as a web/mail URL is kept as a link rather than text.
    nonisolated static func linkString(from text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
              ["http", "https", "mailto", "ftp"].contains(scheme) else { return nil }
        if scheme != "mailto", url.host?.isEmpty ?? true { return nil }
        return trimmed
    }

    // MARK: Polling

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = pasteboard.types?.map(\.rawValue) ?? []
        guard !types.isEmpty else { return }
        if Self.shouldIgnore(types: types) {
            Log.clipboard.debug("cópia ignorada: tipo privado/transitório")
            return
        }
        // Polling cannot see who wrote; the frontmost app at detection time is the best guess
        // (at most 0.5 s late).
        let app = NSWorkspace.shared.frontmostApplication
        if Self.isExcluded(bundleID: app?.bundleIdentifier, excluded: excludedBundleIDs()) {
            Log.clipboard.debug("cópia ignorada: app excluído")
            return
        }
        guard let content = readContent(types: Set(types)) else { return }
        onCapture?(ClipboardCapture(content: content, date: Date(), sourceBundleID: app?.bundleIdentifier, sourceAppName: app?.localizedName))
    }

    /// Files first (Finder also puts names and icons there), then text or link (rich-text apps
    /// also add a rendered image), then a bare image.
    private func readContent(types: Set<String>) -> ClipboardCapture.Content? {
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls.map(\.path))
        }
        if let text = pasteboard.string(forType: .string) {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
            guard text.utf8.count <= Self.maxTextBytes else {
                Log.clipboard.debug("texto acima de 200 KB ignorado")
                return nil
            }
            if let link = Self.linkString(from: text) { return .url(link) }
            return .text(text)
        }
        if let url = pasteboard.string(forType: .URL), let link = Self.linkString(from: url) {
            return .url(link)
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type.rawValue) {
            guard let data = pasteboard.data(forType: type) else { continue }
            guard data.count <= Self.maxImageBytes else {
                Log.clipboard.debug("imagem acima de 20 MB ignorada")
                return nil
            }
            return .image(data)
        }
        return nil
    }
}
